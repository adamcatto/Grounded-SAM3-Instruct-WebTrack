"""Booktabs LaTeX tables for the paper."""

from __future__ import annotations

import math
from pathlib import Path
from typing import Any

from . import _common as C


def _fmt(x, nd=3, pct=False):
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "--"
    return f"{100 * x:.1f}" if pct else f"{x:.{nd}f}"


def _latex_escape(s: str) -> str:
    repl = {"&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#", "$": r"\$"}
    return "".join(repl.get(c, c) for c in str(s))


def table_aggregate(results: dict[str, Any], tab_dir: Path) -> None:
    agg = results.get("aggregate", {})
    if not agg.get("n_videos"):
        return
    median_str = (_fmt(agg["median_collapse_fraction"], pct=True) + r"\% of video"
                  if agg.get("median_collapse_fraction") is not None else "--")
    tex = rf"""% Auto-generated by experiments/vos_comparison/figures
\begin{{table}}[t]
\centering
\caption{{Aggregate single-shot VOS performance against anchor-frame ground truth
over {agg['n_videos']} videos. Anchor labeling holds IoU at 1.0 by construction;
single-shot tracking degrades and collapses on
{_fmt(agg['frac_videos_collapsed'], pct=True)}\% of videos.}}
\label{{tab:vos-aggregate}}
\begin{{tabular}}{{lr}}
\toprule
Metric & Single-shot \\
\midrule
Videos & {agg['n_videos']} \\
Mean IoU & {_fmt(agg['mean_iou'])} $\pm$ {_fmt(agg['std_iou'])} \\
Mean IoU AUC (vs. position) & {_fmt(agg['mean_iou_auc'])} \\
Mean \% frames IoU$\geq\tau$ & {_fmt(agg['mean_frac_above_threshold'], pct=True)} \\
Videos collapsed & {agg['n_collapsed']} / {agg['n_videos']} ({_fmt(agg['frac_videos_collapsed'], pct=True)}\%) \\
Median collapse point & {median_str} \\
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    tab_dir.mkdir(parents=True, exist_ok=True)
    (tab_dir / "table_aggregate.tex").write_text(tex)
    print("[figures]   tables/table_aggregate.tex")


def table_per_video(results: dict[str, Any], tab_dir: Path) -> None:
    videos = results.get("videos", [])
    if not videos:
        return
    rows = []
    for v in sorted(videos, key=lambda d: str(d.get("video_name", "")).lower()):
        cf = v.get("collapse_frame")
        rows.append(" & ".join([
            _latex_escape(v.get("video_name", "")),
            str(v.get("num_scored_frames", "--")),
            _fmt(v.get("mean_iou")),
            _fmt(v.get("median_iou")),
            _fmt(v.get("frac_frames_above_threshold"), pct=True),
            (str(cf) if cf is not None else "--"),
            (_fmt(v.get("collapse_fraction"), pct=True)
             if v.get("collapse_fraction") is not None else "--"),
        ]) + r" \\")
    agg = results.get("aggregate", {})
    body = "\n".join(rows)
    tex = rf"""% Auto-generated by experiments/vos_comparison/figures
\begin{{table}}[t]
\centering
\caption{{Single-shot VOS vs. anchor-frame labeling (ground truth). IoU is the Jaccard
index against the anchor-based track. Collapse = first frame after which IoU stays
below $\tau={_fmt(results.get('threshold'))}$ for the remainder of the video.}}
\label{{tab:vos-per-video}}
\begin{{tabular}}{{lrrrrrr}}
\toprule
Video & Frames & Mean IoU & Median IoU & \% IoU$\geq\tau$ & Collapse frame & Collapse \% \\
\midrule
{body}
\midrule
\textbf{{All ({agg.get('n_videos', 0)})}} & -- & {_fmt(agg.get('mean_iou'))} & -- & {_fmt(agg.get('mean_frac_above_threshold'), pct=True)} & -- & {(_fmt(agg.get('median_collapse_fraction'), pct=True) if agg.get('median_collapse_fraction') is not None else '--')} \\
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    tab_dir.mkdir(parents=True, exist_ok=True)
    (tab_dir / "table_per_video.tex").write_text(tex)
    print("[figures]   tables/table_per_video.tex")


# metrics shown in the by-reduction table: (metric, label, percent)
_ROWS = [
    ("mean_iou", "Mean IoU", False),
    ("collapsed_frac", r"Time collapsed (\% video)", True),
    ("frac_below_thresh", r"Frames IoU$<\tau$ (\%)", True),
    ("frac_zero", r"Frames IoU$=0$ (\%)", True),
    ("zero_collapsed_frac", r"Time at zero IoU (\% video)", True),
    ("collapsed_longest_run", "Longest collapse run (frames)", False),
]


def table_collapse_by_reduction(out_dir: Path, tab_dir: Path) -> None:
    """median [IQR] of each failure metric, per reduction, from aggregate_stats.csv."""
    agg_rows = C.read_csv_dicts(out_dir / "aggregate_stats.csv")
    if not agg_rows:
        return
    idx = {(r["reduction"], r["metric"]): r for r in agg_rows}
    reductions = ["mean", "min", "object"]

    def cell(reduction, metric, pct):
        r = idx.get((reduction, metric))
        if not r:
            return "--"
        med, q1, q3 = C.f(r.get("median")), C.f(r.get("q1")), C.f(r.get("q3"))
        if pct:
            med, q1, q3 = 100 * med, 100 * q1, 100 * q3
            return f"{med:.1f} [{q1:.1f}, {q3:.1f}]"
        return f"{med:.2f} [{q1:.2f}, {q3:.2f}]"

    body_lines = []
    for metric, label, pct in _ROWS:
        cells = " & ".join(cell(red, metric, pct) for red in reductions)
        body_lines.append(f"{label} & {cells} \\\\")
    body = "\n".join(body_lines)
    tex = rf"""% Auto-generated by experiments/vos_comparison/figures
\begin{{table}}[t]
\centering
\caption{{Single-shot VOS failure statistics by object-reduction, as median [IQR]
across videos (per-object pooled across all object tracks). ``Time collapsed'' is the
fraction of the video for which the rolling-average IoU stays below $\tau$ for at least
the minimum run length.}}
\label{{tab:vos-by-reduction}}
\begin{{tabular}}{{lrrr}}
\toprule
Metric & Mean & Min & Per-object \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    tab_dir.mkdir(parents=True, exist_ok=True)
    (tab_dir / "table_collapse_by_reduction.tex").write_text(tex)
    print("[figures]   tables/table_collapse_by_reduction.tex")


def make_tables(out_dir: Path, results: dict[str, Any], tab_dir: Path) -> None:
    table_aggregate(results, tab_dir)
    table_per_video(results, tab_dir)
    table_collapse_by_reduction(out_dir, tab_dir)
